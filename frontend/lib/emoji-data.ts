/**
 * Searches emojis across all categories by matching against the category
 * name or by returning the full list if no query. (This is a simple
 * name-free search — the picker uses the emoji itself as the query key.)
 */
export function searchEmojis(query: string): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  // Simple search across all emojis (returns them in category order)
  const all: string[] = [];
  for (const cat of EMOJI_CATEGORIES) {
    for (const emoji of cat.emojis) {
      all.push(emoji);
    }
  }
  // Since we don't have emoji names, we can't match by text — instead
  // return the full list and let the user scroll. For a real search,
  // use a library like `emojibase` which includes names.
  return q.length === 0 ? [] : all;
}

